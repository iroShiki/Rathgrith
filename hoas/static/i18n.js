const LANG_KEY = 'rathgrith.lang';

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && I18N[saved]) return saved;
  } catch { /* 隐私模式等情况下 localStorage 不可用 */ }
  for (const l of navigator.languages || [navigator.language || '']) {
    const code = l.toLowerCase().split('-')[0];
    if (I18N[code]) return code;
  }
  return 'en';
}

let LANG = detectLang();

function setLang(code) {
  LANG = I18N[code] ? code : 'en';
  try { localStorage.setItem(LANG_KEY, LANG); } catch { /* 同上 */ }
}

// 有数量参数 n 时按当前语言的复数规则选词：英语、芬兰语的单数形式写在 "<key>_one" 里，中文、日语不区分
function t(key, params = {}) {
  if (typeof params.n === 'number' && new Intl.PluralRules(LANGS[LANG].locale).select(params.n) === 'one'
      && I18N[LANG][`${key}_one`]) key = `${key}_one`;
  const s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

const locale = () => LANGS[LANG].locale;

// 把 index.html 里带 data-i18n* 属性的固定文字换成当前语言
function applyStaticText() {
  document.documentElement.lang = locale();
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
